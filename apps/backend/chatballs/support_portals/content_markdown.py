"""Ссылки на файлы статьи внутри Markdown.

Портал отдаётся на своём домене (``help.example.com``), а строгий CSP
документа разрешает картинки только с ``'self'``. Абсолютная ссылка на файл —
пусть даже на ту же установку, но с другим хостом — браузером режется, и
изображение в статье просто не появляется. Поэтому ссылки на файлы статьи
приводятся к относительному виду: и при записи ревизии, и при отдаче — чтобы
вылечился текст, написанный до этого правила.
"""

from __future__ import annotations

import re

# Абсолютный адрес до пути файла статьи: схема и хост отбрасываются, путь
# остаётся. Хост не проверяется — файл всегда отдаётся тем же сайтом.
_ABSOLUTE_FILE_LINK = re.compile(
    r"https?://[^\s)\]<>\"']*?(/api/v1/help/files/[0-9a-fA-F-]{36}/)"
)


def normalize_file_links(content: str) -> str:
    """Сделать ссылки на файлы статьи относительными."""
    return _ABSOLUTE_FILE_LINK.sub(r"\1", content)
